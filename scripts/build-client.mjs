import {execFileSync} from 'node:child_process';
import {mkdir} from 'node:fs/promises';
import {build} from 'esbuild';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
await mkdir(new URL('../build/client/',import.meta.url),{recursive:true});
execFileSync(process.execPath,['node_modules/@tailwindcss/cli/dist/index.mjs','-i','client/styles.css','-o','build/client/tailwind.css','--minify'],{cwd:root,stdio:'inherit',windowsHide:true});
await build({absWorkingDir:root,entryPoints:['client/index.js'],outfile:'plugin/client-runtime.js',bundle:true,format:'iife',target:'es2022',minify:true,
  loader:{'.css':'text'},banner:{js:'// Generated by npm run build:client. Edit client/*.js and client/styles.css.'}});
